def _gguf(pairs: list[bytes]) -> bytes:
    body = b"".join(pairs)
    return b"GGUF" + struct.pack("<I", 3) + struct.pack("<Q", 0) + struct.pack("<Q", len(pairs)) + body


def _text_kv(key: str, value: str) -> bytes:
    raw_key = key.encode()
    raw_value = value.encode()
    return struct.pack("<Q", len(raw_key)) + raw_key + struct.pack("<I", 8) + struct.pack("<Q", len(raw_value)) + raw_value


def _u64_kv(key: str, value: int) -> bytes:
    raw_key = key.encode()
    return struct.pack("<Q", len(raw_key)) + raw_key + struct.pack("<I", 10) + struct.pack("<Q", value)


def _u32_kv(key: str, value: int) -> bytes:
    raw_key = key.encode()
    return struct.pack("<Q", len(raw_key)) + raw_key + struct.pack("<I", 4) + struct.pack("<I", value)


